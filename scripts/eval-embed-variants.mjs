// Copies a vault and its eval file to a scratch directory, so retrieval variants can later be embedded on the copy
// without touching the real vault (spec §10). Run by hand; it ships in no package.
//   node scripts/eval-embed-variants.mjs --from <vault.db> --to <dir> [--eval <path>] [--yes]
// Without --yes it copies, prints how many texts an embedding run would send, sends nothing and exits 0.
// --from is only ever opened read-only and may sit inside the default state directory (HEADJACK_HOME, else
// ~/.headjack). --to must not: the script exits 2 when it resolves (real paths) inside that directory, or when
// <to>/vault.db already exists. The eval file is --eval, else <directory of --from>/suggest/eval.json; it lands at
// <to>/suggest/eval.json.
//
// Near-duplicate eval rows are added to the eval file by hand, never generated by this script: write realistic prompt
// shapes (the way a person phrases a request for the skill) with every dynamic part replaced by a fake value (no real
// names, paths, repositories, tokens or customer data), draft them locally, and review them before they are used.
import { copyFileSync, existsSync, mkdirSync, realpathSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { stateDir } from '../cli/local-config.mjs';
import { runtimeCheck } from '../lib/local/runtime.mjs';
import { vaultFile } from '../lib/local/schema.mjs';

const USAGE = 'usage: node scripts/eval-embed-variants.mjs --from <vault.db> --to <dir> [--eval <path>] [--yes]';

function fail(message, exitCode) {
  return Object.assign(new Error(message), { exitCode });
}

// realpath of a path that may not exist yet: the deepest existing ancestor is resolved (native, so the on-disk letter
// case wins on a case-insensitive filesystem), the rest is appended.
function realResolve(target) {
  let current = path.resolve(target);
  const rest = [];
  for (;;) {
    try {
      return path.join(realpathSync.native(current), ...rest.reverse());
    } catch (error) {
      if (error?.code !== 'ENOENT' && error?.code !== 'ENOTDIR') throw error;
      const parent = path.dirname(current);
      if (parent === current) return path.join(current, ...rest.reverse());
      rest.push(path.basename(current));
      current = parent;
    }
  }
}

const isInside = (child, parent) => {
  const relative = path.relative(parent, child);
  return relative === '' || (relative.split(path.sep)[0] !== '..' && !path.isAbsolute(relative));
};

// The texts a backfill of the copy would embed: one per content or query chunk of a skill's current version (stored
// chunks are what the backfill re-embeds; vectors are not read, so no sqlite extension is needed). The frontmatter
// and tag texts that the later embedding step adds are not counted here.
function countTexts(DatabaseSync, file) {
  const db = new DatabaseSync(file, { readOnly: true });
  try {
    return Number(db.prepare(
      'select count(*) as n from chunks c join skills s on s.id = c.skill_id and s.current_version_id = c.version_id',
    ).get().n);
  } finally {
    db.close();
  }
}

export async function run({ from, to, evalFile, yes = false, env = process.env, fetchImpl = fetch, log = () => {} } = {}) {
  void fetchImpl; // the embedding step (--yes) uses it; the copy and the dry run send nothing
  if (!from || !to) throw fail(USAGE, 2);
  if (yes) throw fail('--yes (embedding on the copy) is not available yet; run without it for the copy and the text count', 2);
  const source = path.resolve(from);
  if (!existsSync(source)) throw fail(`${source} does not exist`, 2);
  const eval_ = path.resolve(evalFile ?? path.join(path.dirname(source), 'suggest', 'eval.json'));
  if (!existsSync(eval_)) throw fail(`eval file ${eval_} does not exist; pass --eval <path>`, 2);

  const target = realResolve(to);
  const defaultDir = realResolve(stateDir({ env, home: os.homedir() }));
  if (isInside(target, defaultDir)) throw fail(`--to ${target} is inside the default state directory ${defaultDir}`, 2);
  const targetVault = vaultFile(target);
  if (existsSync(targetVault)) throw fail(`${targetVault} already exists`, 2);

  const { DatabaseSync } = await runtimeCheck();
  mkdirSync(path.join(target, 'suggest'), { recursive: true, mode: 0o700 });
  const reader = new DatabaseSync(source, { readOnly: true });
  try {
    reader.exec('PRAGMA busy_timeout = 5000');
    // VACUUM INTO writes only the new file; the source connection stays read-only.
    reader.prepare('VACUUM INTO ?').run(targetVault);
  } finally {
    reader.close();
  }
  copyFileSync(eval_, path.join(target, 'suggest', 'eval.json'));

  const texts = countTexts(DatabaseSync, targetVault);
  log(`copied ${source} to ${targetVault}`);
  log(`a run would send ${texts} texts; dry run, nothing was sent (--yes embeds on the copy)`);
  return { copied: true, texts };
}

function parseArgs(argv) {
  const options = { yes: false };
  const names = { '--from': 'from', '--to': 'to', '--eval': 'evalFile' };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--yes') options.yes = true;
    else if (Object.hasOwn(names, arg)) {
      const value = argv[++i];
      if (!value || value.startsWith('--')) throw fail(USAGE, 2);
      options[names[arg]] = value;
    } else throw fail(USAGE, 2);
  }
  return options;
}

if (process.argv[1] && import.meta.url === pathToFileURL(realpathSync(process.argv[1])).href) {
  try {
    await run({ ...parseArgs(process.argv.slice(2)), log: console.log });
  } catch (error) {
    console.error(error.message);
    process.exit(error.exitCode ?? 1);
  }
}
