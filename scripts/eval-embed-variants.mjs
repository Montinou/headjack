const USAGE = 'usage: node scripts/eval-embed-variants.mjs --from <vault.db> --to <dir> [--eval <path>] [--yes]';

function fail(message, exitCode) {
  return Object.assign(new Error(message), { exitCode });
}

// realpath of a path that may not exist yet: the deepest existing ancestor is resolved (native, so the on-disk letter
// case wins on a case-insensitive filesystem), the rest is appended.
function realResolve(target) {
  let current = path.resolve(target);
  const rest = [];
  for (;;) {
    try {
      return path.join(realpathSync.native(current), ...rest.reverse());
    } catch (error) {
      if (error?.code !== 'ENOENT' && error?.code !== 'ENOTDIR') throw error;
      const parent = path.dirname(current);
      if (parent === current) return path.join(current, ...rest.reverse());
      rest.push(path.basename(current));
      current = parent;
    }
  }
}

const isInside = (child, parent) => {
  const relative = path.relative(parent, child);
  return relative === '' || (relative.split(path.sep)[0] !== '..' && !path.isAbsolute(relative));
};

const MAX_LEN = 1000; // the chunk text cut of lib/skillmd.mjs
const EMBED_BATCH = 64;
const BUSY_TIMEOUT_MS = 5000;
const DEFAULT_EMBED_MODEL = 'openai/text-embedding-3-small';

// The first secret-scan rule a text trips, else null. NUL-separated parts are scanned apart, as the backfill does.
function secretRule(text) {
  const files = String(text).split('\0').map((part, i) => ({ path: `${i}.txt`, data: Buffer.from(part) }));
  return findSecrets(files)[0]?.pattern ?? null;
}

function storedTags(value) {
  try {
    const parsed = JSON.parse(value);
    return Array.isArray(parsed) ? parsed.filter((tag) => typeof tag === 'string' && normalizeTag(tag)) : [];
  } catch {
    return [];
  }
}

// The stored tags plus, for a plugin skill, the tag derived from its plugin_slug (the part before @), unless already named.
function tagList(skill) {
  const tags = storedTags(skill.tags);
  const plugin = skill.plugin_slug ? normalizeTag(String(skill.plugin_slug).split('@')[0]) : '';
  if (plugin && !tags.some((tag) => normalizeTag(tag) === plugin)) tags.push(plugin);
  return tags;
}

// The texts steps (2) and (3) would add, from the current state of the vault: a frontmatter text for each skill whose
// current version has no content chunk equal to the text the reader expects (see expectedFrontmatter), and a tag text for
// each skill with a tag list. Vectors are not read, so no sqlite extension is needed.
function planTexts(db) {
  const skills = db.prepare(
    `select s.id, s.slug, s.name, s.description, s.plugin_slug, s.tags, s.current_version_id as version_id, v.tarball
       from skills s join versions v on v.id = s.current_version_id order by s.id`,
  ).all();
  const contentOf = db.prepare("select text from chunks where skill_id = ? and version_id = ? and kind = 'content'");
  const frontmatter = [];
  const tags = [];
  for (const skill of skills) {
    const ref = { skillId: skill.id, versionId: skill.version_id, slug: skill.slug };
    const expected = expectedFrontmatter(skill, skill.tarball ?? null);
    const has = expected !== null && contentOf.all(skill.id, skill.version_id).some((chunk) => chunk.text === expected);
    if (!has) frontmatter.push({ ...ref, kind: 'frontmatter', text: `${skill.name}: ${skill.description}`.slice(0, MAX_LEN) });
    const list = tagList(skill);
    if (list.length) tags.push({ ...ref, kind: 'tags', text: `${skill.name}: ${skill.description} | tags: ${list.join(', ')}`.slice(0, MAX_LEN) });
  }
  return { frontmatter, tags };
}

// What a run would send, read from the fresh copy: the stored chunk texts the backfill re-embeds (one per content or
// query chunk of a skill's current version), the frontmatter and tag texts of steps (2) and (3) (an upper bound: a skill
// the backfill gives a chunk, or a text that trips the secret scan, drops out), and the skills the backfill would send
// to the chat model for Spanish queries.
function countTexts(DatabaseSync, file) {
  const db = new DatabaseSync(file, { readOnly: true });
  try {
    const texts = Number(db.prepare(
      'select count(*) as n from chunks c join skills s on s.id = c.skill_id and s.current_version_id = c.version_id',
    ).get().n);
    const enrich = Number(db.prepare(
      'select count(*) as n from skills where current_version_id is not null and (enrichment_v is null or enrichment_v < ?)',
    ).get(ENRICHMENT_VERSION).n);
    const plan = planTexts(db);
    return { texts, enrich, frontmatterTexts: plan.frontmatter.length, tagTexts: plan.tags.length };
  } finally {
    db.close();
  }
}

// Embeds in order, EMBED_BATCH texts a request. Rejects with the fixed, content-free message of embedTexts.
async function embedAll(texts, { key, fetchImpl, model }) {
  const vectors = [];
  for (let i = 0; i < texts.length; i += EMBED_BATCH) {
    vectors.push(...await embedTexts({ texts: texts.slice(i, i + EMBED_BATCH), key, fetchImpl, model }));
  }
  return vectors;
}

// Steps (2) to (4) on the backfilled copy. Everything is embedded before the first write, and the rows land in one
// transaction, so a failed request leaves the copy as the backfill left it and writes no sidecar.
async function embedVariants({ DatabaseSync, target, key, env, fetchImpl, loadVec, log }) {
  const db = new DatabaseSync(vaultFile(target), { allowExtension: true });
  try {
    db.exec(`pragma busy_timeout = ${BUSY_TIMEOUT_MS}`);
    db.exec('pragma foreign_keys = ON');
    if (!loadVec(db)) throw fail('sqlite-vec is unavailable; nothing was embedded', 2);
    const plan = planTexts(db);
    const skipped = [];
    const sendable = (items) => items.filter((item) => {
      const rule = secretRule(item.text);
      if (rule === null) return true;
      skipped.push({ slug: item.slug, kind: item.kind, rule });
      log(`skipped ${item.slug} (${item.kind}): secret scan flagged ${rule}`);
      return false;
    });
    const items = [...sendable(plan.frontmatter), ...sendable(plan.tags)];
    log(`sending ${items.length} frontmatter and tag texts to the AI Gateway`);
    let vectors;
    try {
      vectors = await embedAll(items.map((item) => item.text), { key, fetchImpl, model: env.EMBED_MODEL || DEFAULT_EMBED_MODEL });
    } catch (error) {
      throw fail(`embedding the frontmatter and tag texts failed (${error.message}); the copy has no sidecar`, 1);
    }

    const insertChunk = db.prepare('insert into chunks (skill_id, version_id, text, kind) values (?, ?, ?, ?) returning id');
    const insertVec = db.prepare('insert into chunk_vecs(rowid, embedding, skill_id, version_id) values (?, ?, ?, ?)');
    const entries = [];
    db.exec('BEGIN IMMEDIATE');
    try {
      items.forEach((item, index) => {
        const chunkId = Number(insertChunk.get(item.skillId, item.versionId, item.text, item.kind === 'tags' ? 'query' : 'content').id);
        insertVec.run(BigInt(chunkId), JSON.stringify(vectors[index]), BigInt(item.skillId), BigInt(item.versionId));
        entries.push({ skill_id: item.skillId, version_id: item.versionId, chunk_id: chunkId, kind: item.kind });
      });
      db.exec('COMMIT');
    } catch (error) {
      if (db.isTransaction) db.exec('ROLLBACK');
      throw error;
    }
    const sidecar = path.join(target, SIDECAR_FILE);
    writeFileSync(sidecar, `${JSON.stringify(entries, null, 2)}\n`, { mode: 0o600 });
    log(`wrote ${entries.length} entries to ${sidecar}`);
    return { sidecar, entries, skipped };
  } finally {
    db.close();
  }
}

export async function run({
  from, to, evalFile, yes = false, env = process.env, fetchImpl = fetch, log = () => {}, loadVec = defaultLoadVec,
} = {}) {
  if (!from || !to) throw fail(USAGE, 2);
  const source = path.resolve(from);
  if (!existsSync(source)) throw fail(`${source} does not exist`, 2);
  const eval_ = path.resolve(evalFile ?? path.join(path.dirname(source), 'suggest', 'eval.json'));
  if (!existsSync(eval_)) throw fail(`eval file ${eval_} does not exist; pass --eval <path>`, 2);

  const target = realResolve(to);
  const defaultDir = realResolve(stateDir({ env, home: os.homedir() }));
  if (isInside(target, defaultDir)) throw fail(`--to ${target} is inside the default state directory ${defaultDir}`, 2);
  const targetVault = vaultFile(target);
  if (existsSync(targetVault)) throw fail(`${targetVault} already exists`, 2);

  const { DatabaseSync } = await runtimeCheck();
  // Consent and prerequisites are checked before anything is copied: a refused --yes leaves no half-made copy.
  let key = null;
  if (yes) {
    key = await aiGatewayKey({ dir: target, env });
    if (!key) throw fail('no AI Gateway key: set AI_GATEWAY_API_KEY (no key file is read); nothing was copied or sent', 2);
    const probe = new DatabaseSync(':memory:', { allowExtension: true });
    try {
      if (!loadVec(probe)) throw fail('sqlite-vec is unavailable; nothing was copied or sent', 2);
    } finally {
      probe.close();
    }
  }

  mkdirSync(path.join(target, 'suggest'), { recursive: true, mode: 0o700 });
  const reader = new DatabaseSync(source, { readOnly: true });
  try {
    reader.exec('PRAGMA busy_timeout = 5000');
    // VACUUM INTO writes only the new file; the source connection stays read-only.
    reader.prepare('VACUUM INTO ?').run(targetVault);
  } finally {
    reader.close();
  }
  copyFileSync(eval_, path.join(target, 'suggest', 'eval.json'));
  log(`copied ${source} to ${targetVault}`);

  if (!yes) {
    const counts = countTexts(DatabaseSync, targetVault);
    log(`a run would send ${counts.texts} texts; dry run, nothing was sent (--yes embeds on the copy)`);
    log(`a run would also send up to ${counts.frontmatterTexts} frontmatter and ${counts.tagTexts} tag texts, and ask the chat model for Spanish queries for ${counts.enrich} skills`);
    return { copied: true, ...counts };
  }

  log('embedding on the copy: skill text is sent to the AI Gateway (consent given with --yes)');
  const code = await embedCommand({ dir: target, env, fetchImpl, log, loadVec });
  if (code !== 0) throw fail(`the backfill of the copy exited ${code}; remove ${targetVault} and rerun`, code === 2 ? 2 : 1);
  const embedded = await embedVariants({ DatabaseSync, target, key, env, fetchImpl, loadVec, log });
  return { copied: true, ...embedded };
}

function parseArgs(argv) {
  const options = { yes: false };
  const names = { '--from': 'from', '--to': 'to', '--eval': 'evalFile' };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--yes') options.yes = true;
    else if (Object.hasOwn(names, arg)) {
      const value = argv[++i];
      if (!value || value.startsWith('--')) throw fail(USAGE, 2);
      options[names[arg]] = value;
    } else throw fail(USAGE, 2);
  }
  return options;
}

if (process.argv[1] && import.meta.url === pathToFileURL(realpathSync(process.argv[1])).href) {
  try {
    await run({ ...parseArgs(process.argv.slice(2)), log: console.log });
  } catch (error) {
    console.error(error.message);
    process.exit(error.exitCode ?? 1);
  }
}
